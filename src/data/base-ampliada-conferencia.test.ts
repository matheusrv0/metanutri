describe('CA-1711: lista de conferência', () => {
  it('tem pelo menos 150 alimentos, sem repetir', () => {
    expect(LISTA.length).toBeGreaterThanOrEqual(150)
    expect(new Set(LISTA.map(([a]) => a)).size).toBe(LISTA.length)
  })

  it.each(LISTA.filter(([, , falta]) => falta === null).map(([a, termo]) => [a, termo] as const))('%s está coberto (busca "%s")', (_alimento, termo) => {
    expect(filtrarCatalogo({ termo }, BASE).length).toBeGreaterThan(0)
  })

  it.each(LISTA.filter(([, , falta]) => falta !== null).map(([a, termo, falta]) => [a, termo, falta ?? ''] as const))('%s falta (busca "%s"): %s', (_alimento, termo, falta) => {
    expect(falta.trim()).not.toBe('')
    expect(filtrarCatalogo({ termo }, BASE)).toEqual([])
  })
})
